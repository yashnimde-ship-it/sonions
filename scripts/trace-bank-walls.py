"""Traces the bank's walls from its reference art into map/bankWalls.mjs.

The bank's walls are thin cream lines (unlike the other maps' dark bands, which
map/artWalls.mjs finds). A wall is a long straight run of cream pixels, so this keeps
cream runs at least RUN px long, horizontally or vertically, which drops the speckled
lobby floor. Each 8 px collision cell a wall line covers enough of becomes solid; the
cells are merged into boxes (in tiles) that map/bankLayout.mjs adds to its WALLS.

Run: python scripts/trace-bank-walls.py   (then npm run bank)"""
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage as nd

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / 'public' / 'reference' / 'bank-reference.png'
OUT = ROOT / 'map' / 'bankWalls.mjs'
TILE, CELL, RUN = 16, 8, 20
# Where cream lines are decoration, not walls (tiles): the lobby's floor emblem and pattern,
# the vault's gold, the teller counter's trim (the counter is a solid of its own).
NOT_WALLS = [
    (17.6, 33.6, 61.4, 47.8),
    (76.6, 11.2, 93.4, 37.2),
    (33.0, 19.8, 58.6, 34.0),
    # Outside: the steps' edges and the paving are cream too (the front wall is in the layout).
    (0.0, 68.8, 96.0, 74.0),
    (36.0, 62.6, 56.0, 68.8),
    # The strip under the vault (drawn as the vault wall's face) is the corridor to its door.
    (74.0, 38.9, 93.0, 40.2),
]

im = np.asarray(Image.open(REF).convert('RGB')).astype(int)
R, G, B = im[..., 0], im[..., 1], im[..., 2]
spread = np.maximum(np.maximum(R, G), B) - np.minimum(np.minimum(R, G), B)
cream = (R >= 225) & (G >= 200) & (B >= 160) & (spread <= 95)
lines = nd.binary_opening(cream, structure=np.ones((1, RUN))) | nd.binary_opening(cream, structure=np.ones((RUN, 1)))
for x0, y0, x1, y1 in NOT_WALLS:
    lines[int(y0 * TILE):int(y1 * TILE), int(x0 * TILE):int(x1 * TILE)] = False

h, w = lines.shape
cw, ch = w // CELL, h // CELL
cover = lines[: ch * CELL, : cw * CELL].reshape(ch, CELL, cw, CELL).mean(axis=(1, 3))
solid = cover >= 0.2

boxes = []
for cy in range(ch):
    cx = 0
    while cx < cw:
        if not solid[cy, cx]:
            cx += 1
            continue
        start = cx
        while cx < cw and solid[cy, cx]:
            cx += 1
        k = TILE // CELL
        boxes.append((start / k, cy / k, cx / k, (cy + 1) / k))

body = ',\n'.join(f'  [{x0:g}, {y0:g}, {x1:g}, {y1:g}]' for x0, y0, x1, y1 in boxes)
OUT.write_text(
    '// Generated by scripts/trace-bank-walls.py from public/reference/bank-reference.png: the\n'
    "// bank's cream wall lines as collision boxes (tiles, end exclusive). Don't edit by hand.\n\n"
    f'export const BANK_WALLS = [\n{body},\n];\n',
    encoding='utf8',
)
print(f'{OUT.relative_to(ROOT)}: {len(boxes)} boxes, {int(solid.sum())} solid cells')
