import fs from 'node:fs';
import { encode } from 'fast-png';
import { loadReference } from './map/referenceExtract.mjs';
import { artWallMask } from './map/artWalls.mjs';
import * as L from './map/museumLayout.mjs';
const ref = loadReference(L.REFERENCE);
const inB = (x, y) => L.BUILDING.some(([x0, y0, x1, y1]) => x >= x0 * 16 && x < x1 * 16 && y >= y0 * 16 && y < y1 * 16);
const wall = artWallMask(ref, null, { region: inB, windows: [], wallLum: +process.argv[3] || 46 });
const out = new Uint8Array(ref.w * ref.h * 4);
for (let i = 0; i < ref.w * ref.h; i++) out.set(wall[i] ? [255, 40, 40, 255] : [ref.rgb[i * 3], ref.rgb[i * 3 + 1], ref.rgb[i * 3 + 2], 255], i * 4);
fs.writeFileSync(process.argv[2], encode({ width: ref.w, height: ref.h, data: out, channels: 4, depth: 8 }));
